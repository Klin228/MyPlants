-- Разрешение на индексацию страницы коллекции поисковиками.
--
-- Отдельная колонка, а не вывод из чего-то ещё: остальные флаги публикации
-- выражаются тем, каких полей в снимке нет, а этот управляет не содержимым, а
-- доступностью для поисковых роботов.
--
-- По умолчанию false — как и все флаги приватности. Существующие коллекции,
-- опубликованные до этой миграции, останутся закрытыми от индексации, и это
-- правильное поведение: согласия на неё никто не давал.

alter table collections
  add column if not exists allow_indexing boolean not null default false;
