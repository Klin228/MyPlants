-- Ограничение частоты публикаций.
--
-- Маршрут публикации открыт: аккаунтов нет. Без учёта попыток хранилище и база
-- наполняются кем угодно и чем угодно.
--
-- Считаем в Postgres, а не в памяти процесса: функции Vercel живут по одной на
-- запрос, и счётчик в памяти не переживёт даже двух подряд. Ключа-значения
-- вроде Redis в проекте нет, а публикация происходит редко — одна запись на
-- попытку базу не обременит.

create table if not exists publish_attempts (
  id          bigserial primary key,

  -- Хеш адреса, а не сам адрес. Нам нужно только различать источники, а
  -- хранить чужие IP-адреса без нужды — ровно то, чего проект избегает.
  client_hash text not null,

  attempted_at timestamptz not null default now()
);

-- Запрос всегда один: сколько попыток с этого источника за последнее время
create index if not exists publish_attempts_by_client
  on publish_attempts (client_hash, attempted_at desc);
