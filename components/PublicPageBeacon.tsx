'use client'

/**
 * Счётчик публичной страницы и ссылка «создать свою».
 *
 * Почему клиентский компонент на странице, про которую в C5 записано «ни одной
 * строчки клиентского кода». Две причины, и обе стоит проверить, а не принять на
 * веру:
 *
 * 1. `'use client'` не значит «только в браузере» — такой компонент всё равно
 *    отрисовывается на сервере. Ссылка приезжает готовой в HTML, и требование
 *    «страница работает без JavaScript» не нарушено. Проверено разметкой
 *    ответа.
 * 2. Клиентская обвязка на этой странице загружается и так: в корневом макете
 *    живёт `ServiceWorkerRegister`, он клиентский. Новый рантайм не появляется,
 *    добавляются сотни байт.
 *
 * Смысл счётчика: `public_page_viewed` — знаменатель главной воронки продукта,
 * а нажатие на ссылку — переход от «посмотрел чужую» к «делаю свою». Без них
 * ключевую метрику посчитать нечем.
 */

import { useEffect } from 'react'
import { track } from '@/lib/analytics'

/**
 * Отметка «пришёл по чужой ссылке», которую читает главный экран.
 *
 * `sessionStorage`, а не адрес страницы: не хочется вешать метку на ссылку,
 * которую человек может куда-то скопировать. И не `document.referrer` — он
 * пропадает при переходе через промежуточные страницы, а нам нужен факт «этот
 * человек пришёл из чужой коллекции», живущий до конца сессии.
 */
const REFERRAL_KEY = 'myplants-from-referral'

export default function PublicPageBeacon() {
  useEffect(() => {
    track({ name: 'public_page_viewed' })
  }, [])

  return (
    <a
      href="/"
      onClick={() => {
        track({ name: 'public_page_cta_clicked' })
        sessionStorage.setItem(REFERRAL_KEY, '1')
      }}
    >
      Made with MyPlants — build your own collection
    </a>
  )
}
