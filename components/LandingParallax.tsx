'use client'

/**
 * Параллакс карточек коллажа на лендинге (тикет J4).
 *
 * **Почему не средствами CSS.** Первым вариантом стояло расписание прокрутки —
 * `animation-timeline: view()`, затем `scroll(root block)`. Ни строчки скрипта,
 * счёт на стороне браузера, идеально по замыслу. Проверить не удалось: в одном
 * случае прогресс замирал на краю диапазона и не отвечал на прокрутку, в другом
 * расписание оказывалось неактивным и сдвиг не применялся вовсе. Может, дело в
 * сборке браузера, может — в моей ошибке; выяснить это здесь нечем, а механизм,
 * который нельзя проверить, в продукт не идёт.
 *
 * Здесь же всё измеримо: значение считается на главном потоке, его видно
 * замером, и оно одинаково работает и в Safari, и в старых браузерах.
 *
 * Цена — клиентский компонент на серверной странице. Он ничего не рисует,
 * только двигает уже отрисованное: без JavaScript коллаж стоит на месте, и
 * страница от этого не теряет ничего, кроме движения.
 */

import { useEffect } from 'react'

/**
 * Насколько сильно карточки расходятся. Множитель к собственному `--drift`
 * карточки: на экране высотой 800 полный размах достигается примерно за
 * половину экрана прокрутки — дальше карточек уже не видно.
 */
const REACH = 0.6

export default function LandingParallax() {
  useEffect(() => {
    /*
     * Движение по прокрутке — первое, что выключают люди с вестибулярными
     * расстройствами. Проверка до всякой работы: слушателя не будет вовсе.
     */
    if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return

    const cards = Array.from(document.querySelectorAll<HTMLElement>('.collage-card'))
    if (cards.length === 0) return

    // Величина сдвига у каждой карточки своя — она задана в CSS вместе с
    // наклоном, чтобы все параметры одной карточки лежали в одном месте.
    const drifts = cards.map((card) => parseFloat(getComputedStyle(card).getPropertyValue('--drift')) || 0)

    let frame = 0

    const apply = () => {
      frame = 0
      // Ноль в начале страницы: карточки стоят ровно там, где их положила
      // раскладка, и расходятся уже от прокрутки. Начальный сдвиг выглядел бы
      // как ошибка вёрстки у того, кто не прокрутил.
      const progress = Math.min(window.scrollY / (window.innerHeight * REACH), 1.5)

      cards.forEach((card, index) => {
        card.style.translate = `0 ${(drifts[index] * progress).toFixed(1)}px`
      })
    }

    /*
     * Обработчик только назначает кадр, а считает `requestAnimationFrame`.
     * Прокрутка на телефоне вызывает событие десятки раз за кадр, и запись
     * стиля на каждое из них — верный способ уронить частоту кадров ровно в тот
     * момент, когда человек оценивает, живая страница или нет.
     */
    const onScroll = () => {
      if (frame === 0) frame = requestAnimationFrame(apply)
    }

    apply()
    window.addEventListener('scroll', onScroll, { passive: true })

    return () => {
      window.removeEventListener('scroll', onScroll)
      if (frame !== 0) cancelAnimationFrame(frame)
      // Возврат в исходное: компонент может быть снят при переходе внутри
      // приложения, и оставленный сдвиг застыл бы навсегда.
      cards.forEach((card) => {
        card.style.translate = ''
      })
    }
  }, [])

  return null
}
