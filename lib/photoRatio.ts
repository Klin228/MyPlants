/**
 * Форма рамки фотографии.
 *
 * Решение тикета X5: рамка берёт пропорцию **у самой фотографии**, а не у общего
 * токена. Живые снимки коллекции портретные — сняты с телефона, растение занимает
 * кадр вертикально, — и фиксированные 4:3 оставляли от них среднюю горизонтальную
 * полосу: верхние листья и горшок уходили под обрез, то есть срезалось именно то,
 * по чему растение узнают.
 *
 * Два правила, без которых «как снято» ломает раскладку:
 *
 * 1. **Форму задаёт обложка — первая фотография растения.** Остальные кадрируются
 *    в неё. Иначе карточка меняет высоту прямо во время свайпа, а в сетке тянет за
 *    собой соседей по строке.
 * 2. **Пропорция зажата.** Панорама 16:9 превратила бы карточку в полоску, а
 *    вертикальный скриншот 9:16 — в столб на весь экран. Внутри пределов кадр
 *    показывается как снят, выбросы подрезаются по короткой стороне.
 *
 * Модуль общий для карточки и витрины намеренно: кроп у них обязан совпадать,
 * иначе владелец кадрирует под одно, а гость по ссылке видит другое. Раньше это
 * обеспечивал общий токен `--photo-ratio`; теперь токен остаётся значением по
 * умолчанию для фотографий, чьих размеров мы не знаем.
 */

/** Предел вытянутости по вертикали: 3:4, портретный кадр телефона. */
export const FRAME_RATIO_MIN = 3 / 4

/** Предел по горизонтали: 4:3, обычный горизонтальный кадр. */
export const FRAME_RATIO_MAX = 4 / 3

/**
 * Пропорция по умолчанию — когда размеров нет.
 *
 * Так выглядит карточка фотографии, сохранённой до версии 3 базы, в тот короткий
 * миг, пока размеры не обмерены, и растения без фотографий. Квадрат выбран как
 * середина между пределами: любое уточнение сдвинет рамку минимально.
 */
export const FRAME_RATIO_DEFAULT = 1

export interface PhotoShape {
  width: number
  height: number
}

/**
 * Пропорция рамки для фотографии: ширина, поделённая на высоту.
 *
 * Возвращает число, а не строку: его же использует предсказание высоты карточки в
 * кладке, и держать одно значение в двух видах — способ однажды разойтись.
 */
export function frameRatio(shape?: PhotoShape | null): number {
  if (!shape || !(shape.width > 0) || !(shape.height > 0)) return FRAME_RATIO_DEFAULT

  const ratio = shape.width / shape.height

  return Math.min(FRAME_RATIO_MAX, Math.max(FRAME_RATIO_MIN, ratio))
}
