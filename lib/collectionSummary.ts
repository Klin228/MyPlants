/**
 * Сводка коллекции: сколько в ней растений.
 *
 * Раньше сюда входило и число видов — «6 plants · 4 species». Владелец убрал его
 * после проверки на живой коллекции, и причина не в лишнем слове: поле вида
 * необязательное, заполняют его не всегда, а сводка считала виды только среди
 * заполненных. Шесть растений с одним заполненным полем давали «6 plants · 1
 * species» — то есть строка сообщала не разнообразие коллекции, а то, сколько раз
 * человек нашёл силы заполнить поле. Ложное показание хуже отсутствующего.
 *
 * Само поле вида осталось: по нему работает поиск, и оно уезжает в публикацию.
 * Ушёл только счётчик в сводке.
 *
 * Модуль намеренно без серверных зависимостей: им пользуются и серверная витрина
 * с картинкой превью, и клиентский главный экран.
 */

/**
 * Сводка по частям — для мест, где она идёт не строкой, а столбиком.
 *
 * Массив, а не строка, хотя часть сейчас одна: плотная шапка на главной и на
 * витрине раскладывает сводку по строкам, и место для второй строки там уже есть.
 * Возвращать одну строку и разбирать её обратно было бы хуже.
 */
export function collectionLines(plantCount: number): string[] {
  return [`${plantCount} ${plantCount === 1 ? 'plant' : 'plants'}`]
}

/**
 * Оговорка к сумме: сколько растений без цены (тикет J5).
 *
 * Отдельно от `collectionLines`, и это не мелочь раскладки. Столбик шапки — имя,
 * сумма, число растений — набран крупно, `12vw` при `line-height: 0.88`, и это
 * голос продукта. Оговорка, попав туда, кричала громче самой суммы: проверено на
 * отрисованной странице, «1 without a price» переносилось на две строки и
 * занимало треть экрана. Сноска и должна выглядеть сноской.
 *
 * Нужна она при этом обязательно: рядом стоит сумма, и без оговорки та врёт
 * умолчанием. Двадцать растений с ценой у трёх дают уверенное «$430», которое
 * читается как стоимость коллекции, а не как стоимость трёх её растений.
 *
 * `null`, когда цены есть у всех: говорить нечего.
 */
export function pricesCaveat(withoutPrice: number): string | null {
  if (withoutPrice <= 0) return null
  return `${withoutPrice} ${withoutPrice === 1 ? 'plant has' : 'plants have'} no price yet`
}

/** Та же сводка одной строкой — для описания страницы и картинки превью. */
export function describeCollection(plantCount: number): string {
  return collectionLines(plantCount).join(' · ')
}
