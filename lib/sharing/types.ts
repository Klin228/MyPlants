/**
 * Что именно уезжает на сервер при публикации коллекции.
 *
 * Здесь описан контракт, а не удобная копия локальной модели. Разница
 * существенная: `Plant` — это всё, что приложение знает о растении, а снимок —
 * то, чем пользователь осознанно решил поделиться. Всё, чего нет в этих типах,
 * на сервер не попадает никогда.
 *
 * Публикация бессрочная (см. `DECISIONS.md`, раздел 1), поэтому снимки будут
 * жить годами и переживут не одну правку формата — отсюда `version`.
 */

/**
 * Версия формата снимка.
 *
 * Поднимается при любом несовместимом изменении: старые опубликованные
 * коллекции никуда не денутся, и читающий код должен понимать, что ему
 * досталось. Пока формат один.
 */
export const SNAPSHOT_VERSION = 1

/**
 * Что из личного пользователь разрешил показать.
 *
 * Все поля выключены по умолчанию — это не удобство, а требование
 * `CLAUDE.md`: поделился значит согласился, а не «забыл снять галочку».
 * Собирать объект руками не надо, для этого есть `DEFAULT_PUBLISH_OPTIONS`.
 */
export interface PublishOptions {
  /**
   * Цены растений и суммарная стоимость коллекции.
   *
   * Самое чувствительное из всего: сумма говорит о доходах владельца, а
   * заодно делает коллекцию интересной тем, кому не стоит знать домашний
   * адрес.
   */
  includePrices: boolean

  /**
   * Заметки.
   *
   * Свободный текст, содержимое которого предугадать нельзя: там бывает и
   * «любит влажность», и «подарок от Маши на годовщину».
   */
  includeNotes: boolean

  /**
   * Источник — откуда растение взялось.
   *
   * Магазин показать не страшно, а вот «черенок от соседки Иры» называет
   * человека, который на это не подписывался.
   */
  includeSource: boolean

  /**
   * Пускать ли поисковики на страницу коллекции.
   *
   * Стоит особняком от трёх флагов выше: те решают, какие поля уедут, этот —
   * кто сможет найти уже уехавшее. Ссылка секретна тем, что её нельзя
   * угадать, и человек, отправивший её двоим друзьям, соглашался именно на
   * это, а не на выдачу в поиске по своему имени.
   */
  allowIndexing: boolean
}

export const DEFAULT_PUBLISH_OPTIONS: PublishOptions = {
  includePrices: false,
  includeNotes: false,
  includeSource: false,
  allowIndexing: false,
}

/**
 * Фотография в опубликованном снимке.
 *
 * `path` — путь в блоб-хранилище, не полный адрес: домен хранилища меняется
 * вместе с проектом, и прибивать его к данным незачем.
 *
 * Размеры нужны публичной странице, чтобы зарезервировать место под картинку
 * до её загрузки — иначе вёрстка прыгает, а это ровно то, от чего избавляемся
 * в тикете D5. Плюс по ним считается сетка OG-картинки в C6.
 */
export interface SnapshotPhoto {
  path: string
  width: number
  height: number
}

/**
 * Растение в опубликованном снимке.
 *
 * Чего здесь намеренно нет:
 *
 * - **локального `id`** — он не нужен серверу и незачем давать возможность
 *   сопоставлять публикации между собой по совпадению идентификаторов;
 * - **`createdAt` и `updatedAt`** — это следы поведения владельца в
 *   приложении, а не свойства растения. Возраст экземпляра в коллекции
 *   выражает `acquiredOn`, и его пользователь заполняет сам;
 * - **`speciesKey`** — считается на сервере из `species` тем же
 *   `lib/species.ts`. Присылать ключ с клиента значит доверять клиенту
 *   нормализацию, по которой потом сопоставляются чужие коллекции.
 */
export interface SnapshotPlant {
  name: string
  species?: string
  /** Только при `includePrices` */
  price?: number
  acquiredOn?: string
  /** Только при `includeSource` */
  source?: string
  /** Только при `includeNotes` */
  notes?: string
  photos: SnapshotPhoto[]
  /**
   * Порядок в коллекции, от нуля.
   *
   * Явное поле вместо сортировки по дате на стороне читателя: публичная
   * страница показывает коллекцию так, как её видел владелец, и не должна
   * ради этого получать его временные метки.
   */
  position: number
}

/**
 * Снимок коллекции целиком — тело запроса на публикацию.
 */
export interface CollectionSnapshot {
  version: number
  /** Как коллекция называется. Не имя владельца: имён мы не собираем. */
  title?: string
  /** Только при `includePrices`: сумма по всем растениям снимка. */
  totalPrice?: number
  /**
   * Разрешил ли владелец поисковикам индексировать страницу.
   *
   * Единственный из флагов публикации, который доезжает до сервера значением:
   * остальные три выражаются тем, каких полей в снимке нет. Поле
   * необязательное, поэтому `SNAPSHOT_VERSION` не поднимается — версия
   * существует для несовместимых изменений, а добавление необязательного поля
   * читатели переживают.
   */
  allowIndexing?: boolean
  plants: SnapshotPlant[]
}

/**
 * Заготовка снимка — то, что отдаёт сборщик до загрузки фотографий.
 *
 * Отличается от `CollectionSnapshot` одним: вместо `SnapshotPhoto` с путями и
 * размерами тут лежат ключи фотографий в IndexedDB. Пути и размеры появляются
 * только после сжатия и загрузки в хранилище — это тикет C3, он и превратит
 * заготовку в снимок.
 *
 * Два типа вместо одного с необязательными полями: так невозможно случайно
 * отправить на сервер заготовку с локальными ключами вместо путей.
 */
export interface SnapshotDraftPlant extends Omit<SnapshotPlant, 'photos'> {
  /** Ключи в IndexedDB, не пути в хранилище */
  photoKeys: string[]
}

export interface CollectionSnapshotDraft {
  version: number
  title?: string
  totalPrice?: number
  allowIndexing?: boolean
  options: PublishOptions
  plants: SnapshotDraftPlant[]
}
