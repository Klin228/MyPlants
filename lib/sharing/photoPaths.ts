/**
 * Пути фотографий в блоб-хранилище.
 *
 * Общий код клиента и сервера: клиент по этим правилам строит путь, сервер по
 * ним же проверяет, что ему прислали. Держать правило в одном месте
 * обязательно — маршрут выдачи токена не имеет никакой авторизации, и
 * проверка пути это единственное, что не даёт писать в хранилище что угодно
 * куда угодно.
 */

/** Папка публикуемых фотографий. */
const PUBLIC_PHOTO_PREFIX = 'c'

/** SHA-256 в шестнадцатеричном виде плюс расширение. */
const PUBLIC_PHOTO_PATH = /^c\/[0-9a-f]{64}\.jpg$/

/**
 * Максимум на одну фотографию. 1200 пикселей по длинной стороне в JPEG 0.82
 * это обычно 150–400 КБ; два мегабайта — потолок с большим запасом, чтобы
 * отсечь попытки загрузить через этот маршрут что-то другое.
 */
export const MAX_PUBLIC_PHOTO_BYTES = 2 * 1024 * 1024

export function publicPhotoPath(hash: string): string {
  return `${PUBLIC_PHOTO_PREFIX}/${hash}.jpg`
}

export function isPublicPhotoPath(path: string): boolean {
  return PUBLIC_PHOTO_PATH.test(path)
}
