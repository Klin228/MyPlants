/**
 * Метка «этот человек пришёл с чужой публичной коллекции».
 *
 * Ставится на публичной странице при нажатии на кнопку (`PublicPageBeacon`),
 * снимается в момент, когда человек завёл первое растение — там же считается
 * `collection_from_referral`, числитель главной метрики продукта.
 *
 * До тикета J3 метку читала только аналитика. Теперь её читает ещё и пустой
 * экран: пришедшему по ссылке нужен другой текст, чем пришедшему самому. Ключ
 * вынесен сюда, чтобы у строки было одно место, а не три копии в разных файлах.
 *
 * **Значение ключа не переименовывать.** Метка живёт в `sessionStorage`, и у
 * человека с открытой вкладкой смена имени означает потерянный переход —
 * ровно тот, ради измерения которого всё и заведено (оговорка тикета J1).
 */

export const REFERRAL_KEY = 'myplants-from-referral'

/**
 * Пришёл ли человек с чужой коллекции.
 *
 * Отвечает `false` где угодно, кроме браузера, и при недоступном хранилище:
 * приватный режим Safari умеет бросать на `sessionStorage`, а ошибка здесь
 * стоила бы главного экрана.
 */
export function cameFromSharedCollection(): boolean {
  if (typeof window === 'undefined') return false

  try {
    return sessionStorage.getItem(REFERRAL_KEY) === '1'
  } catch {
    return false
  }
}
