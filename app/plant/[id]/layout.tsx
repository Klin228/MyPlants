/**
 * Только ради цвета браузерной обвязки на экранах растения (тикет H7).
 *
 * Владелец увидел на телефоне сиреневую полосу над фотографией и назвал её
 * «розовым зазором». В вёрстке зазора нет: замерено на 390×733 с подставленными
 * инсетами iPhone — `.plant-photos` начинается на нулевой строке, фотография
 * тоже, ни один элемент сверху ничего не отступает.
 *
 * Полосу рисует сам Safari. В портрете его адресная строка внизу, а область
 * статуса сверху **не входит в вьюпорт страницы** — поэтому `safe-area-inset-top`
 * там ноль, — и Safari закрашивает её значением `theme-color`. Взято оно из
 * `--color-bg`, то есть ровно тот сиреневый: на главной он продолжает страницу и
 * незаметен, а над фотографией во всю ширину читается как щель.
 *
 * Единственный рычаг здесь — `theme-color`, из CSS до этой полосы не достать.
 * Значение — цвет подложки под фотографией (`--color-surface-empty`): полоса
 * перестаёт быть чужой и читается как паспарту кадра.
 *
 * **Почему не чёрная в обеих темах**, хотя так делает системная галерея: цвет
 * значков статуса — времени и заряда — выбирает система по яркости этой самой
 * полосы, и проверить её выбор мне здесь нечем. Тёмная полоса в светлой теме
 * рискует дать тёмные значки на тёмном. Полоса по теме такого риска не создаёт.
 *
 * Слой охватывает и форму правки (`[id]/edit`) — отдельного способа нет,
 * `viewport` объявляют только серверные модули, а экран растения клиентский. Там
 * это не вредит: полоса стала на полтона отличаться от липкой шапки вместо
 * сиреневого.
 *
 * Держать в паре с `--color-surface-empty` в `globals.css`.
 */

